"""Generate Unicode character classes for QML versions without property escapes.

Numeric Unicode property data: see THIRD_PARTY_NOTICES.md. No runtime Python.
"""
from pathlib import Path
import unicodedata
import json

root = Path(__file__).resolve().parents[1]
ranges = []
start = previous = None
last_kind = None
for cp in range(0x110000):
    category = unicodedata.category(chr(cp))[0]
    kind = 2 if category == 'M' else 1 if category in ('L', 'N') else 0
    if kind != last_kind:
        if last_kind:
            ranges.extend([start, cp - 1, last_kind])
        start, last_kind = cp, kind
if last_kind:
    ranges.extend([start, 0x10FFFF, last_kind])
text = '''// Generated by tools/generate-unicode-tokens.py. Do not edit by hand.
// Unicode property data: see THIRD_PARTY_NOTICES.md; algorithm AGPL-3.0-or-later.
export const unicodeVersion = VERSION;
const ranges = RANGES;
export function characterKind(cp) {
    let lo=0,hi=ranges.length/3-1;
    while(lo<=hi){const mid=(lo+hi)>>>1,i=mid*3;
        if(cp<ranges[i])hi=mid-1;else if(cp>ranges[i+1])lo=mid+1;else return ranges[i+2];}
    return 0;
}
// These scripts commonly omit spaces. Use base-character + combining-mark
// units, not a whole sentence. This is a deterministic matching fallback,
// not a claim of linguistic word segmentation for every supported language.
export function denseScript(cp) {
    return (cp>=0x3400&&cp<=0x9fff)||(cp>=0x20000&&cp<=0x323af)||
        (cp>=0x3040&&cp<=0x30ff)||(cp>=0x31f0&&cp<=0x31ff)||
        (cp>=0xe00&&cp<=0xeff)||(cp>=0x1780&&cp<=0x17ff)||
        (cp>=0x1000&&cp<=0x109f)||(cp>=0xaa60&&cp<=0xaa7f);
}
export function tokenize(text) {
    const out=[];let start=-1,end=0,dense=false;
    function flush(){if(start>=0){out.push({word:text.slice(start,end).normalize('NFKC').toLowerCase(),start,length:end-start});start=-1;}}
    for(let i=0;i<text.length;){const cp=text.codePointAt(i),size=cp>0xffff?2:1,kind=characterKind(cp);
        if(kind===2||cp===0x200c||cp===0x200d){if(start>=0)end=i+size;}
        else if(kind===1){const nextDense=denseScript(cp);if(start>=0&&(dense||nextDense))flush();if(start<0)start=i;end=i+size;dense=nextDense;}
        else flush();
        i+=size;
    }
    flush();return out;
}
'''.replace('VERSION', json.dumps(unicodedata.unidata_version)).replace('RANGES',json.dumps(ranges,separators=(',',':')))
for target in ['desktop/unicode-tokens.mjs','desktop/plasma/contents/ui/unicode-tokens.mjs']:
    (root / target).write_text(text)
print('Generated Unicode',unicodedata.unidata_version,'classes:',len(ranges)//3,'ranges')
