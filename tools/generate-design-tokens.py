"""Generate web tokens from the same semantic source used by native design.
Run from any directory. Does not load npm packages or modify the source tokens.
"""
import json
from pathlib import Path
ROOT = Path(__file__).resolve().parent.parent
source = json.loads((ROOT / 'design/tokens.json').read_text())
def kebab(name):
    return ''.join('-' + c.lower() if c.isupper() else c for c in name)
# The website reads only its own group; the app's themes come from the same values (tools/derive-palette.py).
lines = ['/* Generated by tools/generate-design-tokens.py. Edit design/tokens.json. */', ':root {']
for name, value in source['site'].items():
    lines.append(f'  --site-{kebab(name)}: {value};')
lines += ['}', '']
(ROOT / 'site/assets/tokens.css').write_text('\n'.join(lines))

header = ['// SPDX-License-Identifier: AGPL-3.0-or-later', '// Generated by tools/generate-design-tokens.py. Edit design/tokens.json.', '// clang-format off', '#pragma once', 'namespace Design {']
fields = list(source['palette']['light'])
header.append('struct Palette { ' + ' '.join('const char *'+name+';' for name in fields) + ' };')
for theme, values in source['palette'].items():
    header.append('inline constexpr Palette '+theme+' = {' + ','.join(json.dumps(values[name]) for name in fields) + '};')
# Native metrics in pixels: spacing steps, corner radius and control height.
header.append('namespace Metric {')
for step, value in source['space'].items():
    header.append(f'inline constexpr int space{step} = {int(value.removesuffix("px"))};')
header.append(f'inline constexpr int radius = {source["native"]["buttonRadius"]};')
header.append(f'inline constexpr int control = {source["native"]["controlHeight"]};')
header.append('}')
# Motion durations in milliseconds, the same as the website's.
header.append('namespace Duration {')
for name in ('enter', 'exit', 'press', 'glide', 'reveal'):
    header.append(f'inline constexpr int {name} = {int(source["site"][name].removesuffix("ms"))};')
header.append('}')
header += ['}', '']
(ROOT / 'src').mkdir(exist_ok=True)
# Control glyphs for style sheets (drop-down and spin arrows, check mark), one
# colour per theme, so they stay visible on both palettes.
glyphs = {
    'chevron-down': '<path d="M6 9l6 6 6-6" fill="none" stroke="{c}" stroke-width="2.4" stroke-linecap="round" stroke-linejoin="round"/>',
    'chevron-up': '<path d="M6 15l6-6 6 6" fill="none" stroke="{c}" stroke-width="2.4" stroke-linecap="round" stroke-linejoin="round"/>',
    'check': '<path d="M5 12.5l4.5 4.5L19 7.5" fill="none" stroke="{c}" stroke-width="2.8" stroke-linecap="round" stroke-linejoin="round"/>',
}
glyph_dir = ROOT / 'src/icons/generated'
glyph_dir.mkdir(parents=True, exist_ok=True)
for theme, values in source['palette'].items():
    for name, shape in glyphs.items():
        colour = values['actionText'] if name == 'check' else values['text']
        (glyph_dir / f'{name}-{theme}.svg').write_text(
            '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24">' + shape.format(c=colour) + '</svg>\n')
(ROOT / 'src/design_tokens.h').write_text('\n'.join(header))

# Native shell frontends consume the same semantic source, not copied values.
native = 'export const tokens = ' + json.dumps(source, indent=2) + ';\n'
(ROOT / 'desktop/gnome/tokens.js').write_text(native)
qml = '// Generated; edit design/tokens.json.\nvar tokens = ' + json.dumps(source, indent=2) + ';\n'
(ROOT / 'desktop/plasma/contents/ui/Tokens.js').write_text(qml)

# Keep the browser demonstration on the same tracker and tokenizer.
for filename in ('tracker.mjs', 'unicode-tokens.mjs', 'contrast.mjs'):
    (ROOT / 'site/assets' / filename).write_bytes((ROOT / 'desktop' / filename).read_bytes())
# The mark: the reading line. The cue marker points at the bright current line;
# the lines read and still to come stay dim.
k = source['site']
(ROOT / 'site/assets/mark.svg').write_text(
    f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 32 32"><rect width="32" height="32" rx="8" fill="{k["night"]}"/>'
    f'<path d="M7.5 11.2 12.6 16l-5.1 4.8z" fill="{k["accentNight"]}"/>'
    f'<path d="M16 16h9" stroke="{k["nightText"]}" stroke-width="3" stroke-linecap="round"/>'
    f'<path d="M16 9.5h7M16 22.5h5" stroke="{k["nightControl"]}" stroke-width="2.4" stroke-linecap="round"/></svg>\n')
(ROOT / 'packaging/io.github.brianidavide.kalipso.svg').write_bytes((ROOT / 'site/assets/mark.svg').read_bytes())

n = source['native']
rules=[]
for theme, p in source['palette'].items():
    scope=f'.tp-{theme}'
    rules.append(f"""{scope} {{ background-color: {p['background']}; color: {p['text']}; border: 2px solid {p['border']}; }}
{scope} .tp-muted {{ color: {p['muted']}; }}
{scope} .tp-state {{ color: {p['accent']}; }}
{scope} .tp-pane {{ border-top: 1px solid {p['divider']}; }}
{scope} .tp-editor {{ background-color: {p['surface']}; color: {p['text']}; border: 2px solid {p['border']}; }}
{scope} .tp-editor:focus {{ border-color: {p['focus']}; }}
{scope} .tp-button {{ font-size: {n['labelSize']}pt; font-weight: 500; border-radius: {n['buttonRadius']}px; padding: {source['space']['2']} {source['space']['3']}; min-height: 24px; background-color: {p['surface']}; color: {p['text']}; border: 2px solid {p['border']}; }}
{scope} .tp-button:hover, {scope} .tp-button:active {{ background-color: {p['hover']}; }}
{scope} .tp-button:focus {{ border-color: {p['focus']}; }}
{scope} StEntry:focus {{ box-shadow: inset 0 0 0 2px {p['focus']}; }}
{scope} StScrollBar {{ min-width: 24px; background-color: {p['background']}; }}
{scope} StScrollBar StButton#vhandle, {scope} StScrollBar StButton#hhandle {{ background-color: {p['border']}; min-width:24px; min-height:24px; }}
{scope} .tp-primary {{ min-width: {n['primaryWidth']-28}px; background-color: {p['action']}; color: {p['actionText']}; border-color: {p['action']}; font-weight: bold; }}
{scope} .tp-primary:hover, {scope} .tp-primary:active {{ background-color: {p['actionHover']}; }}
{scope} .tp-quiet {{ background-color: transparent; border-color: transparent; }}
{scope} .tp-quiet:hover, {scope} .tp-quiet:active {{ background-color: {p['hover']}; }}
{scope} .tp-quiet:focus {{ border-color: {p['focus']}; }}
{scope} .tp-button:checked {{ background-color: {p['hover']}; border-color: {p['accent']}; font-weight: bold; }}
{scope} .tp-button:insensitive {{ color: {p['muted']}; border-color: {p['divider']}; }}
{scope} .tp-quiet:insensitive {{ border-color: transparent; }}
{scope} .tp-primary:insensitive {{ background-color: {p['surface']}; }}
{scope} .tp-group-label {{ font-size: {n['labelSize']}pt; font-weight: bold; color: {p['muted']}; padding-top: 4px; }}
{scope} .tp-title {{ color: {p['muted']}; }}
{scope} .tp-progress {{ background-color: {p['divider']}; height: 3px; }}
{scope} .tp-progress-fill {{ background-color: {p['accent']}; height: 3px; }}
{scope} .tp-countdown {{ font-size: {n['readerSize'] * 2}pt; font-weight: bold; color: {p['text']}; background-color: {p['surface']}; border: 1px solid {p['border']}; border-radius: 12px; padding: 8px 24px; }}
""")
rules.append('.tp-button-content { spacing: 6px; }\n.tp-button-icon { icon-size: 16px; }\n')
(ROOT / 'desktop/gnome/stylesheet.css').write_text('/* Generated from design/tokens.json. */\n'+'\n'.join(rules))

(ROOT / 'desktop/plasma/contents/ui/contrast.mjs').write_bytes((ROOT / 'desktop/contrast.mjs').read_bytes())
